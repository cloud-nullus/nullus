package domain

// RestoredFromBackupAnnotation 은 복구가 만든 볼륨에 그 출처를 남기는 표시다.
//
// 설치 preflight 는 네임스페이스에 볼륨이 남아 있으면 설치를 막는다 —
// 새 설치가 옛 데이터베이스를 물려받으면 이번에 만든 비밀번호와 어긋나고,
// 그 사실이 한참 뒤 엉뚱한 도구의 오류로 드러나기 때문이다.
//
// 그런데 **복구가 방금 놓아둔 볼륨**은 사정이 다르다. 복구는 볼륨과 함께
// 그 시점의 Secret 과 금고(OpenBao)까지 되돌리므로 비밀번호가 어긋나지
// 않는다. 막아야 할 것은 "실패한 설치의 잔여" 이지 "복구된 상태" 가 아니다.
//
// 두 경우를 구분할 근거가 볼륨 자체에 있어야 한다 — 네임스페이스 밖의
// 기록에 의존하면 그 기록이 사라진 뒤에는 다시 구분할 수 없다.
//
// 값은 백업 실행 ID 다. 남은 볼륨이 **모두 같은 백업에서 왔을 때만** 통과시킨다
// (설계 §6.1). 섞여 있으면 어느 시점의 상태인지 말할 수 없으므로 막는다.
const RestoredFromBackupAnnotation = "backup.nullus.io/restored-from"
