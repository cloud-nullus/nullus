import { QueryClient, QueryClientProvider } from '@tanstack/react-query'
import { fireEvent, render, screen, waitFor } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { api } from '../../../lib/api'
import { AssistantPanel } from './assistant-panel'

vi.mock('../../../lib/api', () => ({
  api: { get: vi.fn(), post: vi.fn() },
}))

const enabled = { data: { enabled: true, provider: 'upstage', model: 'solar-pro4' } }

function renderPanel(path = '/stack/list') {
  const client = new QueryClient({ defaultOptions: { queries: { retry: false } } })
  return render(
    <QueryClientProvider client={client}>
      <MemoryRouter initialEntries={[path]}>
        <AssistantPanel />
      </MemoryRouter>
    </QueryClientProvider>,
  )
}

async function openPanel() {
  fireEvent.click(await screen.findByRole('button', { name: 'AI assistant' }))
}

beforeEach(() => {
  vi.mocked(api.get).mockReset()
  vi.mocked(api.post).mockReset()
})

describe('AssistantPanel', () => {
  // 키가 없는 서버(또는 엔드포인트가 없는 옛 서버)는 버튼을 그리지 않는다.
  it('renders nothing when the assistant is not configured', async () => {
    vi.mocked(api.get).mockResolvedValue({ data: { enabled: false } } as never)
    const { container } = renderPanel()
    await waitFor(() => expect(api.get).toHaveBeenCalledWith('/assistant/status'))
    expect(container).toBeEmptyDOMElement()
  })

  it('renders nothing when the status cannot be read', async () => {
    vi.mocked(api.get).mockRejectedValue({ status: 404, message: 'Not Found' })
    const { container } = renderPanel()
    await waitFor(() => expect(api.get).toHaveBeenCalled())
    expect(container).toBeEmptyDOMElement()
  })

  it('answers a suggested question with the page as context and lists the tools it used', async () => {
    vi.mocked(api.get).mockResolvedValue(enabled as never)
    vi.mocked(api.post).mockResolvedValue({
      data: { reply: 'devsecops failed at the harbor step.', tools: [{ name: 'stack_list', ok: true }, { name: 'stack_status', ok: false }] },
    } as never)
    renderPanel()
    await openPanel()

    expect(screen.getByText(/solar-pro4/)).toBeInTheDocument()
    // 결과가 외부 모델로 나간다는 것을 공급자 이름으로 밝힌다.
    expect(screen.getByText(/Answers are generated by Upstage\./)).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Are any stacks failing?' }))

    expect(await screen.findByText('devsecops failed at the harbor step.')).toBeInTheDocument()
    expect(api.post).toHaveBeenCalledWith(
      '/assistant/chat',
      { messages: [{ role: 'user', content: 'Are any stacks failing?' }], context: { path: '/stack/list' } },
      expect.objectContaining({ signal: expect.any(AbortSignal) }),
    )
    expect(screen.getByText('Tools used: stack_list · stack_status (failed)')).toBeInTheDocument()
  })

  // 화면이 대화를 들고 있다 — 다음 질문은 앞의 답까지 보낸다.
  it('sends the whole conversation on a follow-up question', async () => {
    vi.mocked(api.get).mockResolvedValue(enabled as never)
    vi.mocked(api.post)
      .mockResolvedValueOnce({ data: { reply: 'One stack failed.', tools: [] } } as never)
      .mockResolvedValueOnce({ data: { reply: 'Harbor timed out.', tools: [] } } as never)
    renderPanel()
    await openPanel()

    const input = screen.getByRole('textbox', { name: 'Message' })
    fireEvent.change(input, { target: { value: 'Any failures?' } })
    fireEvent.keyDown(input, { key: 'Enter' })
    await screen.findByText('One stack failed.')

    fireEvent.change(input, { target: { value: 'Why?' } })
    fireEvent.click(screen.getByRole('button', { name: 'Send' }))
    await screen.findByText('Harbor timed out.')

    expect(vi.mocked(api.post).mock.calls[1][1]).toEqual({
      messages: [
        { role: 'user', content: 'Any failures?' },
        { role: 'assistant', content: 'One stack failed.' },
        { role: 'user', content: 'Why?' },
      ],
      context: { path: '/stack/list' },
    })
  })

  it('does not send on Shift+Enter or with an empty message', async () => {
    vi.mocked(api.get).mockResolvedValue(enabled as never)
    renderPanel()
    await openPanel()

    const input = screen.getByRole('textbox', { name: 'Message' })
    fireEvent.keyDown(input, { key: 'Enter' })
    fireEvent.change(input, { target: { value: 'line one' } })
    fireEvent.keyDown(input, { key: 'Enter', shiftKey: true })
    expect(api.post).not.toHaveBeenCalled()
  })

  // 모델 호출 실패는 서버 원문(한국어) 대신 화면 언어로 알린다. 질문은 남아 다시 보낼 수 있다.
  it('explains an upstream failure and keeps the question', async () => {
    vi.mocked(api.get).mockResolvedValue(enabled as never)
    vi.mocked(api.post).mockRejectedValue({ status: 502, message: 'AI 모델 호출에 실패했습니다' })
    renderPanel()
    await openPanel()

    fireEvent.click(screen.getByRole('button', { name: 'Are any stacks failing?' }))
    expect(await screen.findByText('The AI model did not respond. Try again in a moment.')).toBeInTheDocument()
    expect(screen.getByText('Are any stacks failing?')).toBeInTheDocument()
  })

  it('starts a new conversation', async () => {
    vi.mocked(api.get).mockResolvedValue(enabled as never)
    vi.mocked(api.post).mockResolvedValue({ data: { reply: 'Nothing failed.', tools: [] } } as never)
    renderPanel()
    await openPanel()

    fireEvent.click(screen.getByRole('button', { name: 'Are any stacks failing?' }))
    await screen.findByText('Nothing failed.')
    fireEvent.click(screen.getByRole('button', { name: 'New conversation' }))

    expect(screen.queryByText('Nothing failed.')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Are any stacks failing?' })).toBeInTheDocument()
  })

  // 패널을 닫았다 열어도 대화는 이어진다 — 새로 고치기 전까지는 화면에 남는다.
  it('keeps the conversation when the panel is closed and reopened', async () => {
    vi.mocked(api.get).mockResolvedValue(enabled as never)
    vi.mocked(api.post).mockResolvedValue({ data: { reply: 'Nothing failed.', tools: [] } } as never)
    renderPanel()
    await openPanel()

    fireEvent.click(screen.getByRole('button', { name: 'Are any stacks failing?' }))
    await screen.findByText('Nothing failed.')
    fireEvent.keyDown(screen.getByRole('dialog'), { key: 'Escape' })
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()

    await openPanel()
    expect(screen.getByText('Nothing failed.')).toBeInTheDocument()
  })

  // 답을 기다리는 중에 새 대화를 시작하면 이전 요청을 끊고 바로 새로 물을 수 있다.
  it('aborts a pending answer when a new conversation starts', async () => {
    vi.mocked(api.get).mockResolvedValue(enabled as never)
    let firstSignal: AbortSignal | undefined
    vi.mocked(api.post)
      .mockImplementationOnce((_url, _body, config) => {
        firstSignal = (config as { signal: AbortSignal }).signal
        return new Promise(() => {}) as never
      })
      .mockResolvedValueOnce({ data: { reply: 'Fresh answer.', tools: [] } } as never)
    renderPanel()
    await openPanel()

    fireEvent.click(screen.getByRole('button', { name: 'Are any stacks failing?' }))
    expect(await screen.findByText('Thinking…')).toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'New conversation' }))

    expect(firstSignal?.aborted).toBe(true)
    expect(screen.queryByText('Thinking…')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Which stack templates are available?' }))
    expect(await screen.findByText('Fresh answer.')).toBeInTheDocument()
  })

  it('explains a timeout', async () => {
    vi.mocked(api.get).mockResolvedValue(enabled as never)
    vi.mocked(api.post).mockRejectedValue({ status: 504, message: 'timeout' })
    renderPanel()
    await openPanel()

    fireEvent.click(screen.getByRole('button', { name: 'Are any stacks failing?' }))
    expect(await screen.findByText('The answer took too long. Try a narrower question.')).toBeInTheDocument()
  })
})
